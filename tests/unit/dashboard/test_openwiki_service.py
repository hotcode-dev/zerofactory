"""Unit tests for dashboard/openwiki_service.py."""

import subprocess
from pathlib import Path

import cron.definitions as defs

from dashboard.openwiki_service import (
    OPENWIKI_RELATIVE_DIR,
    build_openwiki_setup_task_prompt,
    check_board_openwiki_status,
    create_openwiki_setup_task,
)
from dashboard.plugin_api import BoardCreate, create_board


def test_build_openwiki_setup_task_prompt():
    prompt = build_openwiki_setup_task_prompt("test-board")
    assert OPENWIKI_RELATIVE_DIR in prompt
    assert "openwiki" in prompt
    assert "AGENTS.md" in prompt
    assert "test-board" in prompt
    assert "npm install -g openwiki" in prompt
    # The wiki must be generated by the openwiki CLI, never manually, using the
    # `code` subcommand (not the bare top-level flags).
    assert "openwiki code --init" in prompt
    assert "openwiki --init" not in prompt  # bare top-level form must not be used
    # Future refreshes/updates use the `code` subcommand; the --print variant
    # is no longer offered (only `openwiki code --update`).
    assert "openwiki code --update" in prompt
    assert "openwiki code --update --print" not in prompt
    assert "--print" not in prompt
    assert "never manually" in prompt
    assert "manually create" in prompt
    # No fallback to hand-authoring the wiki is offered.
    assert "manually structure" not in prompt
    assert "if non-interactive" not in prompt
    # On CLI failure the worker must block, not improvise.
    assert "BLOCK the task" in prompt
    # Detection/verification keys off the CLI's machine-readable JSON ledger,
    # not the Markdown index.md the CLI also writes.
    assert ".page-manifest.json" in prompt
    assert "machine-readable JSON" in prompt
    # The prompt grounds verification in the CLI's standard artifacts: the
    # machine-readable JSON page ledger plus the canonical quickstart.md
    # entry point, and explicitly bars keying off the Markdown index.md.
    assert "openwiki/quickstart.md" in prompt
    assert "standard" in prompt
    assert "Do NOT key off" in prompt
    assert "index.md" in prompt  # only inside the "Do NOT key off" prohibition


